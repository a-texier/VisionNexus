function cvT(key, vars) {
  const entry = CV_I18N[key]
  let s = entry ? (entry[CV_LANG] || entry.fr) : key
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, vars[k])
  return s
}

// Applique la traduction a tous les elements marques data-i18n / data-i18n-title
// / data-i18n-placeholder du DOM statique. Les chaines construites en JS
// (innerHTML dynamique, toasts, confirm()) utilisent cvT() directement a la
// source, pas ce balayage.
function cvApplyI18n() {
  document.documentElement.lang = CV_LANG
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = cvT(el.getAttribute('data-i18n')) })
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = cvT(el.getAttribute('data-i18n-title')) })
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = cvT(el.getAttribute('data-i18n-placeholder')) })
}
